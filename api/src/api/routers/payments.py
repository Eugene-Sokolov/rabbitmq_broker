from typing import Annotated
from uuid import UUID

from data.repositories.payments import PaymentCreate
from fastapi import APIRouter, Depends, Header, status

from api.dependencies import PaymentServiceDep, verify_api_key
from api.schemas.payments import (
    ErrorResponse,
    PaymentAcceptedResponse,
    PaymentCreateRequest,
    PaymentResponse,
)


router = APIRouter(
    prefix="/api/v1/payments",
    tags=["payments"],
    dependencies=[Depends(verify_api_key)],
    responses={
        status.HTTP_401_UNAUTHORIZED: {
            "model": ErrorResponse,
            "description": "`X-API-Key` header is missing or invalid.",
        },
    },
)

IdempotencyKey = Annotated[
    str,
    Header(
        alias="Idempotency-Key",
        min_length=1,
        max_length=255,
        description=("Unique key generated by the client for each new payment."),
        examples=["5f0c1a8e-3b9d-4c1e-9a77-2d4b8f6e1c10"],
    ),
]


@router.post(
    "",
    status_code=status.HTTP_202_ACCEPTED,
    description=(
        "Accepts a payment for asynchronous processing and returns immediately with status "
        "`pending`. The result is delivered to `webhook_url` once processing finishes.\n\n"
        "Requests are idempotent by `Idempotency-Key`: repeating a request with the same key "
        "and body returns the already created payment instead of creating a new one."
    ),
    responses={
        status.HTTP_409_CONFLICT: {
            "model": ErrorResponse,
            "description": "`Idempotency-Key` was already used with a different request body.",
        },
    },
)
async def create_payment(
    request: PaymentCreateRequest,
    idempotency_key: IdempotencyKey,
    service: PaymentServiceDep,
) -> PaymentAcceptedResponse:
    payment = await service.create_payment(
        PaymentCreate(**request.model_dump(), idempotency_key=idempotency_key)
    )
    return PaymentAcceptedResponse.from_payment(payment)


@router.get(
    "/{payment_id}",
    responses={
        status.HTTP_404_NOT_FOUND: {"model": ErrorResponse},
    },
)
async def get_payment(payment_id: UUID, service: PaymentServiceDep) -> PaymentResponse:
    return PaymentResponse.from_payment(await service.get_payment(payment_id))
